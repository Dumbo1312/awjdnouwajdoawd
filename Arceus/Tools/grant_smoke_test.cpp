//
// grant_smoke_test.cpp — standalone validation of the offline-grant RSA path.
//
// Verifies that the EXACT client verification code (Base64Decode +
// RsaVerifyPkcs1Sha256, copied 1:1 from Core/ServerSecureClient.cpp against
// Utilities/OfflineGrantKey.h) accepts a signature produced by the server
// private key (.NET test vector) and rejects tampered payloads/signatures.
//
// Build: see Tools/grant_smoke_build.bat (or cl.exe with bcrypt.lib).
//

#include <windows.h>
#include <bcrypt.h>
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

#include "..\Utilities\OfflineGrantKey.h"

// ---- test vectors (generated by Tools/make_test_grant.ps1) ----
#include "grant_smoke_vectors.inc"

// ---- 1:1 copy of the client verification core ----
static bool RsaVerifyPkcs1Sha256Core(const std::string& payload,
    const uint8_t* sig, size_t sigLen)
{
    uint8_t hash[32];
    BCRYPT_ALG_HANDLE hHashAlg = NULL;
    if (!BCRYPT_SUCCESS(BCryptOpenAlgorithmProvider(&hHashAlg,
        BCRYPT_SHA256_ALGORITHM, NULL, 0)))
        return false;

    NTSTATUS st = BCryptHash(hHashAlg, NULL, 0,
        reinterpret_cast<PUCHAR>(const_cast<char*>(payload.data())),
        static_cast<ULONG>(payload.size()), hash, sizeof(hash));
    BCryptCloseAlgorithmProvider(hHashAlg, 0);
    if (!BCRYPT_SUCCESS(st)) return false;

    std::vector<uint8_t> keyData(
        sizeof(BCRYPT_RSAKEY_BLOB) + 4 + OfflineGrantKey::kModulusSize);
    auto* hdr = reinterpret_cast<BCRYPT_RSAKEY_BLOB*>(keyData.data());
    hdr->Magic = BCRYPT_RSAPUBLIC_MAGIC;
    hdr->BitLength = static_cast<ULONG>(OfflineGrantKey::kModulusSize * 8);
    hdr->cbPublicExp = 4;
    hdr->cbModulus = static_cast<ULONG>(OfflineGrantKey::kModulusSize);
    hdr->cbPrime1 = 0;
    hdr->cbPrime2 = 0;

    uint8_t* p = keyData.data() + sizeof(BCRYPT_RSAKEY_BLOB);
    p[0] = static_cast<uint8_t>(OfflineGrantKey::kExponent >> 24);
    p[1] = static_cast<uint8_t>(OfflineGrantKey::kExponent >> 16);
    p[2] = static_cast<uint8_t>(OfflineGrantKey::kExponent >> 8);
    p[3] = static_cast<uint8_t>(OfflineGrantKey::kExponent);
    std::memcpy(p + 4, OfflineGrantKey::kModulus, OfflineGrantKey::kModulusSize);

    BCRYPT_ALG_HANDLE hRsa = NULL;
    if (!BCRYPT_SUCCESS(BCryptOpenAlgorithmProvider(&hRsa,
        BCRYPT_RSA_ALGORITHM, NULL, 0)))
        return false;

    BCRYPT_KEY_HANDLE hKey = NULL;
    st = BCryptImportKeyPair(hRsa, NULL, BCRYPT_RSAPUBLIC_BLOB, &hKey,
        keyData.data(), static_cast<ULONG>(keyData.size()), 0);
    BCryptCloseAlgorithmProvider(hRsa, 0);
    if (!BCRYPT_SUCCESS(st)) return false;

    BCRYPT_PKCS1_PADDING_INFO padInfo = { BCRYPT_SHA256_ALGORITHM };
    st = BCryptVerifySignature(hKey, &padInfo, hash, sizeof(hash),
        const_cast<PUCHAR>(sig), static_cast<ULONG>(sigLen), BCRYPT_PAD_PKCS1);

    BCryptDestroyKey(hKey);
    return BCRYPT_SUCCESS(st);
}

int main()
{
    int failures = 0;

    {
        bool ok = RsaVerifyPkcs1Sha256Core(
            std::string(reinterpret_cast<const char*>(kGoodPayload), sizeof(kGoodPayload)),
            kGoodSignature, sizeof(kGoodSignature));
        std::printf("[1] good signature        : %s\n", ok ? "PASS" : "FAIL");
        if (!ok) failures++;
    }
    {
        bool ok = RsaVerifyPkcs1Sha256Core(
            std::string(reinterpret_cast<const char*>(kTamperedPayload), sizeof(kTamperedPayload)),
            kGoodSignature, sizeof(kGoodSignature));
        std::printf("[2] tampered payload      : %s (must FAIL)\n", ok ? "FAIL" : "PASS");
        if (ok) failures++;
    }
    {
        std::vector<uint8_t> badSig(kGoodSignature, kGoodSignature + sizeof(kGoodSignature));
        badSig[3] ^= 0x40;
        bool ok = RsaVerifyPkcs1Sha256Core(
            std::string(reinterpret_cast<const char*>(kGoodPayload), sizeof(kGoodPayload)),
            badSig.data(), badSig.size());
        std::printf("[3] tampered signature    : %s (must FAIL)\n", ok ? "FAIL" : "PASS");
        if (ok) failures++;
    }
    {
        bool ok = RsaVerifyPkcs1Sha256Core(
            std::string(reinterpret_cast<const char*>(kGoodPayload), sizeof(kGoodPayload)),
            kGoodSignature, 32);
        std::printf("[4] truncated signature   : %s (must FAIL)\n", ok ? "FAIL" : "PASS");
        if (ok) failures++;
    }

    std::printf("\n%s (%d failures)\n",
        failures == 0 ? "ALL TESTS PASSED" : "TESTS FAILED", failures);
    return failures == 0 ? 0 : 1;
}