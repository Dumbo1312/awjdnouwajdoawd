"""
Resource encryption tool for Peki Master.
Encrypts all embedded resources (DLLs, models, etc.) with AES-256-GCM
so they cannot be extracted from the .exe without a valid session.

Usage:
  python Tools\ResourceEncryptTool.py
  python Tools\ResourceEncryptTool.py --decrypt  (for testing)
"""

import os
import sys
import hashlib
import json
import struct

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

try:
    from Crypto.Cipher import AES
    from Crypto.Random import get_random_bytes
    HAS_CRYPTO = True
except ImportError:
    HAS_CRYPTO = False
    print("[!] pycryptodome nije instaliran. Instaliraj: pip install pycryptodome")
    print("[!] Koristim fallback AES implementaciju (manje secure, ali radi bez dependenci)")

PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EMBEDDED_DIR = os.path.join(PROJECT_DIR, "Embedded")
ENCRYPTED_DIR = os.path.join(EMBEDDED_DIR, "encrypted")
MASTER_KEY_FILE = os.path.join(PROJECT_DIR, "Tools", "resource_key.bin")
HASH_FILE = os.path.join(PROJECT_DIR, "Tools", "resource_hashes.json")

RESOURCE_LIST = [
    "DirectML.dll",
    "onnxruntime.dll",
    "onnxruntime_providers_shared.dll",
    "graphics-hook64.dll",
    "inject-helper64.exe",
    "fortnite.mdl",
    "node2.json",
    "ghub_mouse.dll",
    "rzctl.dll",
    "makcu-cpp.dll",
]


def generate_master_key():
    key = os.urandom(32)
    with open(MASTER_KEY_FILE, "wb") as f:
        f.write(key)
    print(f"[+] Master key generisan: {key.hex()[:16]}...")
    return key


def load_master_key():
    if os.path.exists(MASTER_KEY_FILE):
        with open(MASTER_KEY_FILE, "rb") as f:
            return f.read()
    return generate_master_key()


def aes_encrypt(data, key):
    if HAS_CRYPTO:
        iv = get_random_bytes(12)
        cipher = AES.new(key, AES.MODE_GCM, nonce=iv)
        ciphertext, tag = cipher.encrypt_and_digest(data)
        return iv + tag + ciphertext
    else:
        import hmac
        iv = os.urandom(16)
        encrypted = bytearray()
        prev = iv
        for i in range(0, len(data), 16):
            chunk = data[i:i+16]
            if len(chunk) < 16:
                chunk = chunk + b'\x00' * (16 - len(chunk))
            block_key = hashlib.sha256(key + prev).digest()[:16]
            enc_chunk = bytes(a ^ b for a, b in zip(chunk, block_key))
            encrypted.extend(enc_chunk)
            prev = enc_chunk
        return iv + bytes(encrypted)


def aes_decrypt(data, key):
    if HAS_CRYPTO:
        iv = data[:12]
        tag = data[12:28]
        ciphertext = data[28:]
        cipher = AES.new(key, AES.MODE_GCM, nonce=iv)
        try:
            return cipher.decrypt_and_verify(ciphertext, tag)
        except Exception as e:
            print(f"[!] GCM verification failed: {e}")
            return None
    else:
        iv = data[:16]
        encrypted = data[16:]
        decrypted = bytearray()
        prev = iv
        for i in range(0, len(encrypted), 16):
            chunk = encrypted[i:i+16]
            block_key = hashlib.sha256(key + prev).digest()[:16]
            dec_chunk = bytes(a ^ b for a, b in zip(chunk, block_key))
            decrypted.extend(dec_chunk)
            prev = chunk
        return bytes(decrypted)


def encrypt_file(input_path, output_path, key):
    with open(input_path, "rb") as f:
        data = f.read()

    file_size = len(data)
    encrypted = aes_encrypt(data, key)

    header = struct.pack("<II", 0x45585230, file_size)
    with open(output_path, "wb") as f:
        f.write(header)
        f.write(encrypted)

    sha256_hash = hashlib.sha256(data).hexdigest()
    orig_size = os.path.getsize(input_path)
    enc_size = os.path.getsize(output_path)

    print(f"  Encrypted: {os.path.basename(input_path)}")
    print(f"    Original: {orig_size} -> Encrypted: {enc_size} bytes")
    print(f"    SHA256: {sha256_hash[:16]}...")

    return sha256_hash, file_size


def decrypt_file(input_path, output_path, key):
    with open(input_path, "rb") as f:
        data = f.read()

    magic, orig_size = struct.unpack("<II", data[:8])
    if magic != 0x45585230:
        print(f"[!] Invalid magic in {input_path}")
        return False

    encrypted = data[8:]
    decrypted = aes_decrypt(encrypted, key)
    if decrypted is None:
        return False

    decrypted = decrypted[:orig_size]

    with open(output_path, "wb") as f:
        f.write(decrypted)

    print(f"  Decrypted: {os.path.basename(input_path)} -> {os.path.basename(output_path)}")
    return True


def get_cpp_header(key, resource_hashes):
    key_hex = ', '.join(f'0x{b:02X}' for b in key)
    lines = []
    lines.append("#pragma once")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("// Auto-generated by ResourceEncryptTool.py")
    lines.append("// DO NOT EDIT MANUALLY")
    lines.append("")
    lines.append("namespace ResourceProtection")
    lines.append("{")
    lines.append("    static constexpr std::size_t MASTER_KEY_SIZE = 32;")
    lines.append(f"    static constexpr uint8_t MASTER_KEY[MASTER_KEY_SIZE] = {{ {key_hex} }};")
    lines.append("")
    lines.append("    static constexpr uint32_t RESOURCE_MAGIC = 0x45585230;")
    lines.append("")
    lines.append("    struct ResourceInfo")
    lines.append("    {")
    lines.append("        int resId;")
    lines.append("        const char* filename;")
    lines.append("        uint32_t originalSize;")
    lines.append("        const char* sha256;")
    lines.append("    };")
    lines.append("")

    for res_name, info in resource_hashes.items():
        var_name = res_name.replace(".", "_").replace("-", "_")
        lines.append(f'    static constexpr const char* SHA256_{var_name} = "{info["sha256"]}";')
    lines.append("")

    lines.append("    static constexpr ResourceInfo RESOURCE_TABLE[] = {")
    for res_name, info in resource_hashes.items():
        var_name = res_name.replace(".", "_").replace("-", "_")
        lines.append(f'        {{ {info["res_id"]}, "{res_name}", {info["orig_size"]}, SHA256_{var_name} }},')
    lines.append("    };")
    lines.append("")
    lines.append(f"    static constexpr std::size_t RESOURCE_COUNT = {len(resource_hashes)};")
    lines.append("}")

    return "\n".join(lines)


def main():
    print("=== Resource Encryption Tool ===")
    print(f"Project: {PROJECT_DIR}")
    print()

    if not os.path.exists(EMBEDDED_DIR):
        print(f"[!] Embedded directory not found: {EMBEDDED_DIR}")
        return 1

    os.makedirs(ENCRYPTED_DIR, exist_ok=True)

    key = load_master_key()
    print(f"[+] Master key loaded: {key.hex()[:16]}...")
    print()

    resource_hashes = {}

    decrypt_mode = "--decrypt" in sys.argv

    if decrypt_mode:
        print("[*] DECRYPT MODE: Vracam original fajlove iz encrypted...")
        for filename in RESOURCE_LIST:
            enc_path = os.path.join(ENCRYPTED_DIR, f"{filename}.enc")
            out_path = os.path.join(EMBEDDED_DIR, filename)
            if os.path.exists(enc_path):
                decrypt_file(enc_path, out_path, key)
        print("[+] Decryption complete.")
        return 0

    # RESOURCE IDs from resource.h
    res_ids = {
        "DirectML.dll": 100,
        "onnxruntime.dll": 101,
        "onnxruntime_providers_shared.dll": 102,
        "graphics-hook64.dll": 103,
        "inject-helper64.exe": 104,
        "fortnite.mdl": 105,
        "node2.json": 106,
        "makcu-cpp.dll": 108,
    }

    print("[*] Encrypting resources...")
    for filename in RESOURCE_LIST:
        input_path = os.path.join(EMBEDDED_DIR, filename)
        if not os.path.exists(input_path):
            print(f"  [!] Skipping (not found): {filename}")
            continue

        output_path = os.path.join(ENCRYPTED_DIR, f"{filename}.enc")
        sha256_hash, orig_size = encrypt_file(input_path, output_path, key)

        resource_hashes[filename] = {
            "sha256": sha256_hash,
            "orig_size": orig_size,
            "res_id": res_ids.get(filename, 0),
        }

    print()

    hash_data = {}
    for name, info in resource_hashes.items():
        hash_data[name] = info
    with open(HASH_FILE, "w") as f:
        json.dump(hash_data, f, indent=2)
    print(f"[+] Hash file written: {HASH_FILE}")

    cpp_header = get_cpp_header(key, resource_hashes)
    header_path = os.path.join(PROJECT_DIR, "Utilities", "ResourceProtection.h")
    with open(header_path, "w") as f:
        f.write(cpp_header)
        f.write("\n")
    print(f"[+] C++ header written: {header_path}")

    print()
    print("=== Zavrseno! ===")
    print()
    print("Next steps:")
    print("  1. Build: fajlovi u Embedded/encrypted/ se koriste umesto raw fajlova")
    print("  2. ResourceExtract ce decryptovati u runtime-u")
    print("  3. Cuvaj Tools/resource_key.bin sigurno!")

    return 0


if __name__ == "__main__":
    sys.exit(main())
