#
# GenOfflineGrantKey.ps1 — generate the offline-grant RSA-2048 keypair.
#
#  - Creates Tools/server_offline_private.pem  (SERVER ONLY — keep secret)
#  - Creates Tools/server_offline_public.pem   (for verification/testing)
#  - Writes Utilities/OfflineGrantKey.h with the PUBLIC modulus+exponent
#    that the client embeds (signature verification, no private material).
#
# The client can only VERIFY signatures; only the server can sign.
# Regenerate ONLY when you want to revoke all existing offline grants.
#
# No external tools needed: keys are generated with .NET RSA and the PEMs are
# encoded as RFC 8017 PKCS#1 DER locally (self-validated on exit).
#

param(
    [string]$ProjectDir = ""
)

if (-not $ProjectDir) { $ProjectDir = (Split-Path $PSScriptRoot -Parent) }
$toolsDir = Join-Path $ProjectDir "Tools"
$utilDir = Join-Path $ProjectDir "Utilities"
New-Item -ItemType Directory -Force -Path $toolsDir | Out-Null
New-Item -ItemType Directory -Force -Path $utilDir | Out-Null

# ---- minimal DER helpers (TLV) ----
function Der-Int([byte[]]$bytes) {
    if ($bytes.Length -gt 0 -and ($bytes[0] -band 0x80)) {
        $bytes = [byte[]](0x00) + $bytes
    }
    return Der-Tlv 0x02 $bytes
}

function Der-LenBytes([int]$n) {
    if ($n -lt 0x80) { return [byte[]]@([byte]$n) }
    elseif ($n -lt 0x100) { return [byte[]]@(0x81, [byte]$n) }
    elseif ($n -lt 0x10000) {
        return [byte[]]@(0x82, [byte](($n -shr 8) -band 0xFF), [byte]($n -band 0xFF))
    }
    throw "unsupported length"
}

function Der-Tlv([int]$tag, [byte[]]$content) {
    return [byte[]]@([byte]$tag) + (Der-LenBytes $content.Length) + $content
}

function Der-Seq([byte[]]$content) { return Der-Tlv 0x30 $content }

function To-Pem([byte[]]$der, [string]$label) {
    $b64 = [System.Convert]::ToBase64String($der)
    $lines = @()
    $lines += "-----BEGIN $label-----"
    for ($i = 0; $i -lt $b64.Length; $i += 64) {
        $len = [Math]::Min(64, $b64.Length - $i)
        $lines += $b64.Substring($i, $len)
    }
    $lines += "-----END $label-----"
    return $lines -join "`r`n"
}

function Trim-Zero([byte[]]$b) {
    $i = 0
    while ($i -lt $b.Length - 1 -and $b[$i] -eq 0) { $i++ }
    return $b[$i..($b.Length - 1)]
}

# ---- generate ----
$rsa = [System.Security.Cryptography.RSA]::Create(2048)
$p = $rsa.ExportParameters($true)

# RFC 8017 RSAPrivateKey: SEQUENCE of INTEGER 0, n, e, d, p, q, dp, dq, qi
$content = $($(Der-Int ([byte[]]@(0))) + $(Der-Int $p.Modulus) + $(Der-Int $p.Exponent) + $(Der-Int $p.D) + $(Der-Int $p.P) + $(Der-Int $p.Q) + $(Der-Int $p.DP) + $(Der-Int $p.DQ) + $(Der-Int $p.InverseQ))
$privDer = Der-Seq $content

# RFC 8017 RSAPublicKey: SEQUENCE of INTEGER n, e
$pubContent = $(Der-Int $p.Modulus) + $(Der-Int $p.Exponent)
$pubDer = Der-Seq $pubContent

# ---- self-validation: decode the DER and compare against .NET numbers ----
function Read-Der([byte[]]$der, [int]$pos, [ref]$nextPos) {
    $tag = $der[$pos]
    $pos++
    $len = $der[$pos]
    $pos++
    if ($len -band 0x80) {
        $numLen = $len -band 0x7F
        $len = 0
        for ($i = 0; $i -lt $numLen; $i++) { $len = ($len -shl 8) -bor $der[$pos + $i] }
        $pos += $numLen
    }
    $content = $der[$pos..($pos + $len - 1)]
    $nextPos.Value = $pos + $len
    return $content
}
$pos = 0
$pubSeq = $(Read-Der $pubDer 0 ([ref]$pos))
$nEnc = $(Read-Der $pubSeq 0 ([ref]$pos))
$eEnc = $(Read-Der $pubSeq $pos ([ref]$pos))
if (-not (([System.Linq.Enumerable]::SequenceEqual([byte[]]$(Trim-Zero $nEnc), [byte[]]$(Trim-Zero $p.Modulus))))) { throw "DER validation failed: modulus mismatch" }
if (-not (([System.Linq.Enumerable]::SequenceEqual([byte[]]$(Trim-Zero $eEnc), [byte[]]$(Trim-Zero $p.Exponent))))) { throw "DER validation failed: exponent mismatch" }
Write-Host "[GrantKey] DER self-validation OK (n/e round-trip)." -ForegroundColor Green

# ---- emit files ----
[System.IO.File]::WriteAllText((Join-Path $toolsDir "server_offline_private.pem"), (To-Pem $privDer "RSA PRIVATE KEY") + "`r`n")
[System.IO.File]::WriteAllText((Join-Path $toolsDir "server_offline_public.pem"), (To-Pem $pubDer "RSA PUBLIC KEY") + "`r`n")

$exp = 0
foreach ($b in $p.Exponent) { $exp = ($exp -shl 8) -bor $b }

$lines = @()
$lines += "// AUTO-GENERATED by Tools/GenOfflineGrantKey.ps1 -- do not edit."
$lines += "#pragma once"
$lines += "#include <cstddef>"
$lines += "#include <cstdint>"
$lines += "namespace OfflineGrantKey"
$lines += "{"
$lines += "    static constexpr uint32_t kExponent = $exp;"
$lines += "    static constexpr size_t kModulusSize = $($p.Modulus.Length);"
$lines += "    static constexpr uint8_t kModulus[$($p.Modulus.Length)] = {"
for ($i = 0; $i -lt $p.Modulus.Length; $i += 16) {
    $chunk = @()
    for ($j = $i; $j -lt [Math]::Min($i + 16, $p.Modulus.Length); $j++) {
        $chunk += ("0x{0:X2}" -f $p.Modulus[$j])
    }
    $lines += "        " + ($chunk -join ", ") + ","
}
$lines += "    };"
$lines += "}"

[System.IO.File]::WriteAllLines((Join-Path $utilDir "OfflineGrantKey.h"), $lines)

Write-Host "[GrantKey] Private : $toolsDir\server_offline_private.pem (SERVER ONLY!)" -ForegroundColor Green
Write-Host "[GrantKey] Public  : $toolsDir\server_offline_public.pem" -ForegroundColor Green
Write-Host "[GrantKey] Header  : $utilDir\OfflineGrantKey.h" -ForegroundColor Green
Write-Host "[GrantKey] WARNING : protect the private key. Client only embeds the public half." -ForegroundColor Yellow