# SecretMutator.ps1
# Generates Core\KeyauxSecret.gen.h with a per-build random XOR key.
# Every build produces different bytes for the secret + fresh TLS certificate pins
# for api.keyaux.com (anti server-emulation via cert pinning).
$ErrorActionPreference = 'Stop'

$toolsDir = $PSScriptRoot
$projectDir = Split-Path -Parent $toolsDir
$secretPath = Join-Path $toolsDir 'secret.txt'
$pinPath = Join-Path $toolsDir 'serverpin.txt'
$headerPath = Join-Path $projectDir 'Core\KeyauxSecret.gen.h'

if (-not (Test-Path $secretPath)) { throw "secret.txt missing at: $secretPath" }
$plain = (Get-Content -LiteralPath $secretPath -Raw).Trim()
$bytes = [System.Text.Encoding]::ASCII.GetBytes($plain)
$len = $bytes.Length
if ($len -eq 0) { throw 'secret.txt is empty' }

$key = New-Object byte[] $len
$rng = New-Object System.Security.Cryptography.RNGCryptoServiceProvider
$rng.GetBytes($key)
$enc = New-Object byte[] $len
$xorsum = [byte]0
for ($i = 0; $i -lt $len; $i++) { $enc[$i] = $bytes[$i] -bxor $key[$i]; $xorsum = $xorsum -bxor $bytes[$i] }

function Get-LivePins {
    try {
        $c = New-Object System.Net.Sockets.TcpClient
        $c.Connect('api.keyaux.com', 443)
        $s = New-Object System.Net.Security.SslStream($c.GetStream(), $false, { $true })
        $s.AuthenticateAsClient('api.keyaux.com')
        $cert = New-Object System.Security.Cryptography.X509Certificates.X509Certificate2($s.RemoteCertificate)
        $sha = [System.Security.Cryptography.SHA256]::Create()
        $full = [BitConverter]::ToString($sha.ComputeHash($cert.RawData)) -replace '-', ''
        $pk = [BitConverter]::ToString($sha.ComputeHash($cert.PublicKey.EncodedKeyValue.RawData)) -replace '-', ''
        $s.Close(); $c.Close()
        return @{ full = $full; pk = $pk }
    } catch { return $null }
}

$pins = $null
try { $pins = Get-LivePins } catch { $pins = $null }
if (-not $pins -and (Test-Path -LiteralPath $pinPath)) {
    $stored = Get-Content -LiteralPath $pinPath
    if ($stored.Count -ge 2) { $pins = @{ full = $stored[0]; pk = $stored[1] } }
}
if (-not $pins) { throw 'cannot obtain TLS pins for api.keyaux.com (no network and no cached pins)' }
Set-Content -LiteralPath $pinPath -Value @($pins.full, $pins.pk)

function To-Arr($hex) {
    $arr = @()
    for ($i = 0; $i -lt $hex.Length; $i += 2) { $arr += '0x' + $hex.Substring($i, 2) }
    return ($arr -join ', ')
}

$fullArr = To-Arr $pins.full
$pkArr = To-Arr $pins.pk
$encArr = ($enc | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', '
$keyArr = ($key | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', '
$xorSumHex = '0x{0:X2}' -f $xorsum

$hdr = @"
// AUTO-GENERATED by Tools\SecretMutator.ps1 - regenerated on every build.
// Per-build mutation: the bytes below change on every build. DO NOT EDIT.
#pragma once
#include <cstddef>
namespace KeyauxSecretGen
{
    constexpr size_t K8_SECRET_LEN = $len;
    constexpr unsigned char K8_SECRET_XOR_SUM = $xorSumHex;
    static const unsigned char K8_ENCODED_SECRET[K8_SECRET_LEN] = { $encArr };
    static const unsigned char K8_SECRET_XOR_KEY[K8_SECRET_LEN] = { $keyArr };
    static const unsigned char K8_PIN_FULLCERT[32] = { $fullArr };
    static const unsigned char K8_PIN_PUBKEY[32] = { $pkArr };
}
"@
Set-Content -LiteralPath $headerPath -Value $hdr -Encoding Ascii
Write-Host "[SecretMutator] regenerated $headerPath (len=$len, xorSum=$xorSumHex)"
