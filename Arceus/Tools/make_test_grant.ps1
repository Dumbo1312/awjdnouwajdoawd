#
# make_test_grant.ps1 — sign a fixed test payload with the server private key
# using pure BigInteger PKCS#1 v1.5 (m = 0x0001FF..00 || DigestInfo(SHA256),
# sig = m^d mod n) and emit C++ test vectors for Tools/grant_smoke_test.cpp.
# No .NET RSA object needed (CAPI ImportParameters quirks on PS 5.1).
#

param([string]$OutCpp = "grant_smoke_vectors.inc")

Add-Type -AssemblyName System.Numerics

$pemPath = Join-Path $PSScriptRoot "server_offline_private.pem"
if (-not (Test-Path -LiteralPath $pemPath)) { throw "private pem missing: $pemPath" }

$pem = [System.IO.File]::ReadAllText($pemPath)
$b64 = (($pem -split "-----BEGIN RSA PRIVATE KEY-----")[1] -split "-----END RSA PRIVATE KEY-----")[0] -replace "\s", ""
$der = [System.Convert]::FromBase64String($b64)

function Read-Der([byte[]]$d, [int]$pos, [ref]$np) {
    $len = $d[$pos + 1]; $s = $pos + 2
    if ($len -band 0x80) {
        $nl = $len -band 0x7F; $len = 0
        for ($i = 0; $i -lt $nl; $i++) { $len = ($len -shl 8) -bor $d[$s + $i] }
        $s += $nl
    }
    $c = $d[$s..($s + $len - 1)]; $np.Value = $s + $len; return $c
}

$pos = 0
$seq = $(Read-Der $der 0 ([ref]$pos))
$pos = 0
$ints = @()
while ($pos -lt $seq.Length) { $ints += , $(Read-Der $seq $pos ([ref]$pos)) }

function BI([byte[]]$be) {
    $b = [byte[]]$be.Clone()
    [Array]::Reverse($b)
    return [System.Numerics.BigInteger]::new($b)
}

$n = BI $ints[1]
$d = BI $ints[3]

function Sign-Pkcs1Sha256([byte[]]$data, [System.Numerics.BigInteger]$n, [System.Numerics.BigInteger]$d) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $hash = $sha.ComputeHash($data)
    $digestInfo = [byte[]](0x30, 0x31, 0x30, 0x0D, 0x06, 0x09, 0x60, 0x86, 0x48,
        0x01, 0x65, 0x03, 0x04, 0x02, 0x01, 0x05, 0x00, 0x04, 0x20)
    $em = [byte[]]::new(256)
    $em[0] = 0x00; $em[1] = 0x01
    for ($i = 2; $i -lt (256 - 19 - 32 - 1); $i++) { $em[$i] = 0xFF }
    $em[256 - 19 - 32 - 1] = 0x00
    [Array]::Copy($digestInfo, 0, $em, 256 - 19 - 32, 19)
    [Array]::Copy($hash, 0, $em, 256 - 32, 32)

    $mLe = [byte[]]$em.Clone()
    [Array]::Reverse($mLe)
    $mInt = [System.Numerics.BigInteger]::new($mLe)
    $sig = [System.Numerics.BigInteger]::ModPow($mInt, $d, $n).ToByteArray()
    if ($sig.Length -gt 256) { $sig = $sig[0..255] }
    while ($sig.Length -lt 256) { $sig = , 0 + $sig }
    [Array]::Reverse($sig)
    return $sig
}

$payload = '{"ts":1752489980,"hwid":"TESTHWID","license":"TESTLICENSE"}'
$payloadBytes = [System.Text.Encoding]::UTF8.GetBytes($payload)
$sig = Sign-Pkcs1Sha256 $payloadBytes $n $d

$tampered = [byte[]]$payloadBytes.Clone()
$tampered[5] = [byte]($tampered[5] -bxor 1)

function To-CppArray([string]$name, [byte[]]$bytes, [int]$perLine) {
    $parts = for ($i = 0; $i -lt $bytes.Length; $i += $perLine) {
        $chunk = @()
        for ($j = $i; $j -lt [Math]::Min($i + $perLine, $bytes.Length); $j++) { $chunk += ("0x{0:X2}" -f $bytes[$j]) }
        "        " + ($chunk -join ", ") + ","
    }
    return "static const uint8_t $name[$($bytes.Length)] = {`r`n" + ($parts -join "`r`n") + "`r`n    };"
}

$lines = @()
$lines += "// AUTO-GENERATED by Tools/make_test_grant.ps1 -- test vectors only."
$lines += To-CppArray "kGoodPayload" $payloadBytes 16
$lines += ""
$lines += To-CppArray "kGoodSignature" $sig 16
$lines += ""
$lines += To-CppArray "kTamperedPayload" $tampered 16

[System.IO.File]::WriteAllLines((Join-Path $PSScriptRoot $OutCpp), $lines)
Write-Host "[GrantTest] vectors -> $OutCpp (256-byte RSA-2048 PKCS1v15-SHA256 sig ok)"
Write-Host "[GrantTest] payload: $payload"